"""
tools/tests/test_generate_sbom.py

TC-SEC-05, Gate S3: the bill of materials lists what ships in the release app, with hashes (BUG-2026-093).
"""

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent.parent
sys.path.insert(0, str(REPO_ROOT / "tools"))

from generate_sbom import generate_cyclonedx_sbom, load_artifact_hashes  # noqa: E402

METADATA = """<?xml version="1.0" encoding="UTF-8"?>
<verification-metadata xmlns="https://schema.gradle.org/dependency-verification">
   <components>
      <component group="com.squareup.okhttp3" name="okhttp" version="4.12.0">
         <artifact name="okhttp-4.12.0.jar"><sha256 value="aaaa" origin="Generated by Gradle"/></artifact>
         <artifact name="okhttp-4.12.0.module"><sha256 value="bbbb" origin="Generated by Gradle"/></artifact>
      </component>
      <component group="androidx.camera" name="camera-core" version="1.5.0">
         <artifact name="camera-core-1.5.0.aar"><sha256 value="cccc" origin="Generated by Gradle"/></artifact>
      </component>
   </components>
</verification-metadata>
"""

LOCK = (
    "# lock\n"
    "com.squareup.okhttp3:okhttp:4.12.0=debugRuntimeClasspath,releaseRuntimeClasspath\n"
    "androidx.camera:camera-core:1.5.0=releaseRuntimeClasspath\n"
    "org.jetbrains.kotlin:kotlin-compiler-embeddable:2.2.10=kotlinCompilerClasspath\n"
    "org.junit.jupiter:junit-jupiter:5.10.0=debugUnitTestRuntimeClasspath,releaseUnitTestRuntimeClasspath\n"
    "empty=\n"
)


def build(tmp_path, **kwargs):
    lock = tmp_path / "gradle.lockfile"
    lock.write_text(LOCK, encoding="utf-8")
    meta = tmp_path / "verification-metadata.xml"
    meta.write_text(METADATA, encoding="utf-8")
    return generate_cyclonedx_sbom(lock, tmp_path / "bom.json", verification_metadata=meta, **kwargs)


def test_only_the_libraries_of_the_release_runtime_are_listed(tmp_path):
    names = {c["name"] for c in build(tmp_path)["components"]}

    assert names == {"okhttp", "camera-core"}


def test_every_configuration_can_still_be_asked_for(tmp_path):
    names = {c["name"] for c in build(tmp_path, configuration=None)["components"]}

    assert {"kotlin-compiler-embeddable", "junit-jupiter"} <= names


def test_each_component_carries_the_hash_of_its_main_artifact_not_its_module_file(tmp_path):
    by_name = {c["name"]: c for c in build(tmp_path)["components"]}

    assert by_name["okhttp"]["hashes"] == [{"alg": "SHA-256", "content": "aaaa"}]
    assert by_name["camera-core"]["hashes"] == [{"alg": "SHA-256", "content": "cccc"}]


def test_a_component_without_metadata_has_no_hash_rather_than_a_made_up_one(tmp_path):
    lock = tmp_path / "gradle.lockfile"
    lock.write_text("com.example:unknown:1.0=releaseRuntimeClasspath\n", encoding="utf-8")

    sbom = generate_cyclonedx_sbom(lock, tmp_path / "bom.json", verification_metadata=tmp_path / "none.xml")

    assert "hashes" not in sbom["components"][0]


def test_the_real_release_lockfile_gives_hashes_for_most_components():
    hashes = load_artifact_hashes(REPO_ROOT / "android" / "gradle" / "verification-metadata.xml")
    sbom = generate_cyclonedx_sbom(
        REPO_ROOT / "android" / "app" / "gradle.lockfile", REPO_ROOT / "android" / "build" / "bom-test.json"
    )

    assert hashes
    assert sbom["components"]
    with_hash = [c for c in sbom["components"] if "hashes" in c]
    assert len(with_hash) >= len(sbom["components"]) * 0.9
